"""Regenerate requirements.lock: requirements.txt's pins, with sha256 hashes of
the files production installs (Python 3.12, Linux x86_64, glibc).

Runs on any machine with network and a recent pip (no Linux needed): pip
downloads the wheels built for that target, and the hashes are taken from them.
The lock holds the pins for Python >= 3.10 (production's). `--no-deps` because
requirements.txt already lists every transitive package; the image build proves
it: `pip install --require-hashes` fails on a dependency the lock does not hold.

    python3 scripts/make_lock.py          # writes requirements.lock
    python3 scripts/make_lock.py --check  # exits 1 when the lock is stale
"""
import hashlib
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ["--python-version", "3.12", "--implementation", "cp", "--abi", "cp312",
          "--platform", "manylinux2014_x86_64", "--platform", "manylinux_2_17_x86_64", "--platform", "manylinux_2_28_x86_64"]
HEADER = """# Generated by scripts/make_lock.py from requirements.txt: do not edit by hand.
# Hashes of the wheels for Python 3.12 on Linux x86_64 (glibc), the Docker image's
# target; the Dockerfile installs with `pip install --require-hashes`.
# Regenerate after any change to requirements.txt (docs/RELEASING.md).
"""


def pins():
    """requirements.txt as Python >= 3.10 reads it: name -> version."""
    out = {}
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line or 'python_version < "3.10"' in line:
            continue
        name, version = line.split(";")[0].strip().split("==")
        out[name.lower()] = version
    return out


def build():
    wanted = pins()
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, "-m", "pip", "download", "--no-deps", "--only-binary=:all:", "-q", "-d", tmp, *TARGET,
                        *[f"{n}=={v}" for n, v in wanted.items()]], check=True)
        hashes = {}
        for f in pathlib.Path(tmp).iterdir():
            name, version = re.split(r"-", f.name)[0:2]
            hashes.setdefault((name.lower().replace("_", "-"), version), []).append(hashlib.sha256(f.read_bytes()).hexdigest())
    lines = []
    for name, version in sorted(wanted.items()):
        found = hashes.get((name.replace("_", "-"), version))
        if not found:
            sys.exit(f"no wheel for {name}=={version} on the target")
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in sorted(found)))
    return HEADER + "\n".join(lines) + "\n"


if __name__ == "__main__":
    text, path = build(), ROOT / "requirements.lock"
    if "--check" in sys.argv:
        sys.exit(0 if path.exists() and path.read_text() == text else 1)
    path.write_text(text)
    print(f"wrote {path.name}: {text.count('--hash=')} hashes")
